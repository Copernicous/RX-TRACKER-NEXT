'use strict';
const assert = require('assert/strict');
const { readArchiveProgress, saveArchiveProgress, nextPendingArchivePage, archivePeriodText } = require('../public/js/archive-downloads');
const { dateRange, filenameDateRange } = require('../utils/archiveDateRange');
const values = new Map(), storage = { getItem: key => values.get(key), setItem: (key,value) => values.set(key,value) };
const meta = { scope: 'section-and-database-and-user-a', revision: '100', totalPages: 48 };
let progress = readArchiveProgress(storage, meta);
assert.equal(nextPendingArchivePage(progress), 1);
progress.page = 24; progress.started = [1,2,24];
assert(saveArchiveProgress(storage, meta, progress));
assert.deepEqual(readArchiveProgress(storage, meta), progress);
assert.equal(nextPendingArchivePage(progress), 3);
assert.deepEqual(readArchiveProgress(storage, { ...meta, scope: 'another-section-or-database-or-user' }).started, []);
assert.deepEqual(readArchiveProgress(storage, { ...meta, revision: '101' }).started, []);
assert.deepEqual(readArchiveProgress(storage, { ...meta, totalPages: 49 }).started, []);
progress.started = [2,2,1,-1,49,1.5,'3']; progress.page = 100;
saveArchiveProgress(storage, meta, progress);
assert.deepEqual(readArchiveProgress(storage, meta).started, [1,2]);
assert.equal(readArchiveProgress(storage, meta).page, 1);
assert.equal(nextPendingArchivePage({ totalPages: 3, started: [3,1,2] }), null);
assert.equal(nextPendingArchivePage({ totalPages: 0, started: [] }), null);
const broken = { getItem() { throw Error('unavailable'); }, setItem() { throw Error('full'); } };
assert.deepEqual(readArchiveProgress(broken, meta).started, []);
assert.equal(saveArchiveProgress(broken, meta, progress), false);
assert(!JSON.stringify(progress).includes('patient'));
const range = dateRange([{ createdAt:'2026-10-02T02:00:00Z' }, { createdAt:'2026-10-01T02:00:00Z' }], 'createdAt');
assert.deepEqual(range, { dateFrom:'2026-10-01T02:00:00.000Z',dateTo:'2026-10-02T02:00:00.000Z' });
assert.equal(filenameDateRange(range,'America/New_York'),'2026-09-30_to_2026-10-01');
assert.equal(archivePeriodText(range,'America/New_York'),'Sep 30, 2026 – Oct 1, 2026');
assert.equal(archivePeriodText({dateFrom:range.dateFrom,dateTo:range.dateFrom},'America/New_York'),'Sep 30, 2026');
assert.equal(archivePeriodText(dateRange([], 'createdAt'),'UTC'),'Date unavailable');
assert.equal(filenameDateRange(dateRange([], 'createdAt'),'UTC'),'undated_to_undated');
console.log('PASS persisted archive progress, section/user/database isolation, archive revision reset, invalid state recovery and next-pending navigation.');
